/** The single figure shown on map hover. */
export const outflowLabel = (market) => {
  if (market.outflow === null || market.outflow === undefined)
    return market.outflowNote || "Unspecified";
  return market.outflow >= 1
    ? `$${market.outflow}B`
    : `$${(market.outflow * 1000).toFixed(0)}M`;
};
